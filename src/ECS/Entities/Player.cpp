Expected<ecs::Entity> createPlayerWithSprite(Sprite sprite) {
    auto expected = System::ecs->entity(false);
    if (!expected.isExpected()) {
        return expected;
    }
    auto player = expected.value();
    auto _ = ecs::DeferActivate(player);

    Transform2D transform = Transform2D::tiles(15, 10);  // TODO get the last level the player was in and spawn in the start point -- or maybe have
                                                         // some SafeLocatoinCheckpoint triggers in the map data
    player.add(transform);
    player.add(Name("Player"));
    player.add<Player>();
    player.add<Velocity>();
    player.add<PlayerControl>();
    player.add<Jumper>();

    if (!getCamera()) {
        createCamera(player);
    }

    // graphics
    Animator animator;
    loadAnimations(animator, PlayerAnim::S_PLAYER_ANIM_INFO);
    animator.brain = &PlayerAnim::brain;
    player.add(animator);

    Frame frame = animator.getFrame();
    sprite.depth = Depth::Player;
    sprite.setFrameSize(frame.dimensionsTexels.x(), frame.dimensionsTexels.y());
    sprite.atlasPositionTexels = frame.atlasPositionTexels;
    player.add(sprite);

    constexpr s32 width = 16;
    // constexpr s32 height = 16;
    constexpr s32 halfLenX = PIXELS_PER_TEXEL * width / 4;
    constexpr s32 halfLenY = PIXELS_PER_TEXEL * 6;
    player.add(ActorCollider(transform, Vector2i(halfLenX, halfLenY)));
    player.add<RigidBody>();
    // player.add<FreeControl>();

    player.add(Respawn{2, &respawnPlayer,
                       []() {
                           System::audio.playClip(Sfx::DEATH);
                           System::audio.setMusicVolume(0.75);
                           System::audio.setFilterMusic(AudioPlayer::Filter::LowPass);
                       },
                       []() {
                           System::audio.setMusicVolume(1);
                           System::audio.setFilterMusic(AudioPlayer::Filter::None);
                       }});

    return player;
}

Expected<ecs::Entity> createPlayer() {
    Sprite sprite;
    return createPlayerWithSprite(sprite);
}

// use sprite with pre-constructed vao/vbo created on main thread
void respawnPlayer(Sprite sprite) {
    Expected<ecs::Entity> player = createPlayerWithSprite(sprite);
    if (!player.isExpected()) {
        print(player.error());
    }
}

