bool brain(Animator& animator, ecs::Entity entity) {
    auto rbOpt = entity.tryGet<RigidBody>();
    RigidBody rb;
    if (rbOpt) {
        rb = *rbOpt.value();
    }

    auto jumperOpt = entity.tryGet<Jumper>();

    auto& vel = entity.get<Velocity>();
    auto& sprite = entity.get<Sprite>();

    f32 unsquishStep = System::dt() * 1.50;
    sprite.scale = {approach(sprite.scale.x(), 1.0, unsquishStep), approach(sprite.scale.y(), 1.0, unsquishStep)};
    if (rb.isGrounded) {
        if (rb.isLanding) {
            f32 squish = std::min(abs(vel.total.y()) / abs(TERMINAL_VELOCITY_Y), 1.0f);
            sprite.scale = {myLerp(1, 1.25, squish), myLerp(1, 0.8, squish)};
            System::audio.playClip(Sfx::LAND, 0.0375 * squish);
        }
        if (vel.total.x() != 0) {
            if (animator.setAnimation(RUN)) {
                System::audio.playClip(Sfx::FOOTSTEPTEST, 0.075);
                return true;
            }
        } else {
            if (animator.setAnimation(IDLE)) {
                return true;
            }
        }
    } else {
        if (jumperOpt && jumperOpt.value()->isJumping) {
            if ((animator.getAnimation().id == JUMP_FORWARD || animator.getAnimation().id == RISE_FORWARD) && vel.total.y() <= 1 &&
                animator.setAnimation(PEAK_FORWARD)) {
                return true;
            }
            // TODO once implemented
            // if (animator.getAnimation().id == JUMP && vel.total.y() <= 1 && animator.setAnimation(PEAK)) {
            //     return true;
            // }

            bool isJumping = [](s32 animId) -> bool {
                switch (animId) {
                case JUMP:
                case JUMP_FORWARD:
                case RISE:
                case RISE_FORWARD:
                case PEAK:
                case PEAK_FORWARD:
                    return true;
                default:
                    return false;
                }
                return false;
            }(animator.getAnimation().id);

            // TODO normal jump
            if (!isJumping && animator.setAnimation(JUMP_FORWARD)) {
                sprite.scale = {0.8, 1.25};
                System::audio.playClip(Sfx::JUMP, 0.35);
                return true;
            }
        } else {
            // falling, switch to peak or fall anim depending on current state
            switch (animator.getAnimation().id) {
            case IDLE:
                return animator.setAnimation(FALL_FORWARD);  // TODO check xVel
            case RUN:
                return animator.setAnimation(FALL_FORWARD);
            case FALL:
                break;
            case FALL_FORWARD:
                break;
            case RISE:
            case JUMP:
                return animator.setAnimation(PEAK);
            case RISE_FORWARD:
            case JUMP_FORWARD:
                return animator.setAnimation(PEAK_FORWARD);
            case PEAK:
                break;  // handled below
            case PEAK_FORWARD:
                break;  // handled below
            }
        }
    }

    // animation did not change
    bool frameChanged = basicAnimation(animator, entity);
    bool animEnded = frameChanged && animator.curFrameIx == 0;
    if (frameChanged && animator.getAnimation().id == RUN && animator.curFrameIx % 2 == 1) {
        System::audio.playClip(Sfx::FOOTSTEPTEST, 0.05);
    }

    // do tween transitions
    if (animEnded) {
        switch (animator.getAnimation().id) {
        case PEAK_FORWARD:
            return animator.setAnimation(FALL_FORWARD);
        case PEAK:
            return animator.setAnimation(FALL);
        case JUMP_FORWARD:
            return animator.setAnimation(RISE_FORWARD);
        case JUMP:
            return animator.setAnimation(RISE);
        default:
            break;
        }
    }

    return frameChanged;
}

