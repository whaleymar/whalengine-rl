// Helper function to normalize angles and avoid costly modulo operations
constexpr int normalize_degrees(f32 degrees) {
    // Convert negative angles into the positive range in one step
    if (degrees < 0) {
        degrees += 360.0 * (1 + static_cast<int>(-degrees / 360.0));
    }

    // Reduce angle to the range [0, 360) without floating point modulo
    return static_cast<int>(degrees) % TABLE_SIZE;
}

f32 fast_sin(f32 radians) {
    int index = normalize_degrees(radians * RAD_TO_DEG);
    return S_SINE_TABLE[index];
}

f32 fast_cos(f32 radians) {
    int index = normalize_degrees(radians * RAD_TO_DEG);
    return S_COS_TABLE[index];
}

f32 normalizeAngle(f32 angle) {
    f32 normalized = fmod(angle, 360.0);
    if (normalized < 0) {
        normalized += 360.0;
    }
    return normalized;
}

f32 getAngleDiff(f32 angle1, f32 angle2) {
    // Normalize both angles to be within [0, 360)
    angle1 = normalizeAngle(angle1);
    angle2 = normalizeAngle(angle2);

    // Calculate the difference
    f32 diff = angle2 - angle1;

    // Normalize the difference to the range [-180, 180]
    if (diff > 180.0) {
        diff -= 360.0;
    } else if (diff < -180.0) {
        diff += 360.0;
    }

    return diff;
}

